test('invalid code cannot accept a session and a transient API failure can be retried', async ({ page }) => {
  let unavailable = true;
  await page.route('**/api/activation/check', route => unavailable ? route.fulfill({ contentType: 'text/html', body: '<html>upstream error</html>' }) : route.continue());
  await page.goto('/'); await expect(page.getByLabel(/账号 session/)).toBeDisabled();
  await page.getByRole('textbox', { name: /兑换卡密/ }).fill(codes[1]);
  await page.getByRole('button', { name: '校验卡密', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('服务响应异常');
  unavailable = false; await page.getByRole('button', { name: '校验卡密', exact: true }).click();
  await expect(page.getByLabel(/账号 session/)).toBeEnabled();
  await page.getByRole('textbox', { name: /兑换卡密/ }).fill('INVALID-CODE-12345678');
  await expect(page.getByLabel(/账号 session/)).toBeDisabled();
  await page.getByRole('button', { name: '校验卡密', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('卡密不存在');
});
